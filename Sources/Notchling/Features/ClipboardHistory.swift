import AppKit
import Combine

/// Opt-in clipboard history. Kept in memory only (never written to disk) and
/// skips anything a password manager marks as concealed or transient.
@MainActor
final class ClipboardHistory: ObservableObject {
    struct Entry: Identifiable, Equatable {
        let id = UUID()
        let text: String
        let date: Date
        let sourceApp: String?
    }

    @Published private(set) var entries: [Entry] = []
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var timer: Timer?
    private var cancellable: AnyCancellable?
    private let maxEntries = 30

    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    init(settings: AppSettings) {
        cancellable = settings.$clipboardHistoryEnabled.sink { [weak self] enabled in
            self?.setRunning(enabled)
        }
    }

    private func setRunning(_ running: Bool) {
        timer?.invalidate()
        timer = nil
        guard running else { entries.removeAll(); return }
        lastChangeCount = NSPasteboard.general.changeCount
        // Checking changeCount is cheap and doesn't read clipboard contents;
        // we only read when something actually changed.
        timer = Timer.scheduledTimer(withTimeInterval: 0.8, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }
        guard let text = pb.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines),
              !text.isEmpty else { return }
        entries.removeAll { $0.text == text }
        entries.insert(Entry(text: text, date: Date(),
                             sourceApp: NSWorkspace.shared.frontmostApplication?.localizedName), at: 0)
        if entries.count > maxEntries { entries.removeLast(entries.count - maxEntries) }
    }

    func copy(_ entry: Entry) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(entry.text, forType: .string)
        lastChangeCount = pb.changeCount
        entries.removeAll { $0.id == entry.id }
        entries.insert(Entry(text: entry.text, date: Date(), sourceApp: entry.sourceApp), at: 0)
    }

    func remove(_ entry: Entry) { entries.removeAll { $0.id == entry.id } }
    func clear() { entries.removeAll() }
}
